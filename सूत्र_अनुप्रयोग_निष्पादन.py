# 🕉️ सूत्र अनुप्रयोग निष्पादन तंत्र


class अनुप्रयोग:


    def __init__(self, नाम, आदेशसूची):

        self.नाम = नाम
        self.आदेशसूची = आदेशसूची

        self.स्थिति = "तैयार"


    def चलाओ(self):

        print(f"अनुप्रयोग प्रारम्भ: {self.नाम}")

        self.स्थिति = "सक्रिय"


        for आदेश in self.आदेशसूची:

            print(f"आदेश निष्पादन: {आदेश}")


        self.स्थिति = "समाप्त"

        print(f"अनुप्रयोग समाप्त: {self.नाम}")



class अनुप्रयोगतंत्र:


    def __init__(self):

        self.अनुप्रयोगसूची = {}

        print("🕉️ सूत्र अनुप्रयोग निष्पादन तंत्र सक्रिय")


    def लोड(self, नाम, आदेशसूची):

        app = अनुप्रयोग(नाम, आदेशसूची)

        self.अनुप्रयोगसूची[नाम] = app

        print(f"अनुप्रयोग लोड हुआ: {नाम}")

        return app


    def निष्पादन(self, नाम):

        if नाम in self.अनुप्रयोगसूची:

            self.अनुप्रयोगसूची[नाम].चलाओ()

        else:

            print("❌ अनुप्रयोग नहीं मिला")
