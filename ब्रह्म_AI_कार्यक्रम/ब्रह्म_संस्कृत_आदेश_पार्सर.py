class ब्रह्मसंस्कृतआदेशपार्सर:

    def __init__(self):
        print("🕉️ ब्रह्म संस्कृत आदेश पार्सर सक्रिय")

    def पार्स(self, पाठ):

        आदेशसूची = []

        पंक्तियाँ = पाठ.split("\n")

        for पंक्ति in पंक्तियाँ:

            पंक्ति = पंक्ति.strip()

            if not पंक्ति:
                continue

            भाग = पंक्ति.split()

            आदेश = भाग[0]

            if आदेश == "संग्रह":

                आदेशसूची.append({
                    "type": "store",
                    "var": भाग[1],
                    "value": int(भाग[2])
                })

            elif आदेश == "योग":

                आदेशसूची.append({
                    "type": "add",
                    "a": भाग[1],
                    "b": भाग[2]
                })

            elif आदेश == "प्रदर्शन":

                आदेशसूची.append({
                    "type": "print",
                    "var": भाग[1]
                })

        return आदेशसूची
