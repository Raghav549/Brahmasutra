# 🕉️ सूत्र मूल प्रणाली

class सूत्रमूल:

    def __init__(self):

        print("🕉️ सूत्र मूल प्रणाली सक्रिय")

        self.संस्करण = "१.०"

        self.घटक = {

            "कर्ण":False,
            "स्मृति":False,
            "प्रक्रिया":False,
            "सञ्चिका":False,
            "यन्त्र":False,
            "संकलक":False,
            "व्याख्याकार":False,
            "द्विआधारी":False,
            "कृत्रिमबुद्धि":False

        }


    def आरम्भ(self):

        print("सूत्र प्रणाली आरम्भ हो रही है")

        for घटक in self.घटक:

            self.घटक[घटक] = True

            print("सक्रिय:", घटक)


        print("सूत्र प्रणाली पूर्ण सक्रिय")


    def स्थिति(self):

        print("सूत्र प्रणाली स्थिति:")

        for घटक in self.घटक:

            print(घटक,":",self.घटक[घटक])
