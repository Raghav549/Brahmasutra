# 🕉️ सूत्र CPU तंत्र

class सूत्रसीपीयू:

    def __init__(self):

        print("🕉️ सूत्र CPU तंत्र सक्रिय")

        self.रजिस्टर = {

            "अ":0,
            "ब":0,
            "स":0,
            "द":0

        }


    def स्थापय(self, रजिस्टर, मान):

        self.रजिस्टर[रजिस्टर] = मान

        print("स्थापित:", रजिस्टर, मान)


    def योग(self, र1, र2):

        self.रजिस्टर[र1] += self.रजिस्टर[र2]

        print("योग:", self.रजिस्टर[र1])


    def दर्शय(self):

        print("रजिस्टर स्थिति:")

        for क in self.रजिस्टर:

            print(क,"=",self.रजिस्टर[क])
