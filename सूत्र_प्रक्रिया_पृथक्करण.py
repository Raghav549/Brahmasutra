# 🕉️ सूत्र प्रक्रिया पृथक्करण तंत्र


class प्रक्रियास्थिति:

    def __init__(self, नाम):

        self.नाम = नाम
        self.स्मृति = {}
        self.सक्रिय = True


class सूत्रप्रक्रियापृथक्करण:


    def __init__(self):

        self.प्रक्रियाएँ = {}

        print("🕉️ प्रक्रिया पृथक्करण तंत्र सक्रिय")


    def निर्माण(self, नाम):

        प्रक्रिया = प्रक्रियास्थिति(नाम)

        self.प्रक्रियाएँ[नाम] = प्रक्रिया

        print("प्रक्रिया निर्मित:", नाम)

        return प्रक्रिया


    def समाप्त(self, नाम):

        if नाम in self.प्रक्रियाएँ:

            self.प्रक्रियाएँ[नाम].सक्रिय = False

            print("प्रक्रिया समाप्त:", नाम)


    def सूची(self):

        print("सक्रिय प्रक्रियाएँ:")

        for नाम, प्रक्रिया in self.प्रक्रियाएँ.items():

            if प्रक्रिया.सक्रिय:

                print("•", नाम)
