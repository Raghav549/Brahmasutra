import time


class मानक:


    def लेखनम्(self, विषय):

        print(विषय)



    def ग्रहणम्(self, संदेश):

        return input(संदेश)



    def दीर्घता(self, वस्तु):

        return len(वस्तु)



    def समयः(self):

        return time.time()



    def पूर्णांक(self, मूल्य):

        return int(मूल्य)
