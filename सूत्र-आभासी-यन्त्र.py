print("🕉️ सूत्र आभासी-यन्त्र सक्रिय")
print("आदेश: सहायता")


# स्मृति
स्मृति = {}


# रजिस्टर
रजिस्टर = {

    "अ": 0,
    "ब": 0,
    "स": 0,
    "द": 0

}


# प्रोग्राम संग्रह
कार्यसूची = []


def दर्शय():

    print("रजिस्टर स्थिति:")

    for नाम in रजिस्टर:

        print(नाम, "=", रजिस्टर[नाम])


def स्मृति_दर्शय():

    print("स्मृति स्थिति:")

    for नाम in स्मृति:

        print(नाम, "=", स्मृति[नाम])


def आदेश_निष्पादन(पंक्ति):

    भाग = पंक्ति.split()

    यदि = भाग[0]


    if यदि == "स्थापय":

        रजिस्टर[भाग[1]] = int(भाग[2])

        print("स्थापित")


    elif यदि == "योग":

        रजिस्टर[भाग[1]] += रजिस्टर[भाग[2]]

        print("योग पूर्ण")


    elif यदि == "घटा":

        रजिस्टर[भाग[1]] -= रजिस्टर[भाग[2]]

        print("घटाव पूर्ण")


    elif यदि == "गुण":

        रजिस्टर[भाग[1]] *= रजिस्टर[भाग[2]]

        print("गुणन पूर्ण")


    elif यदि == "स्मृति":

        स्मृति[भाग[1]] = रजिस्टर[भाग[2]]

        print("स्मृति संग्रहीत")


    elif यदि == "लोड":

        रजिस्टर[भाग[1]] = स्मृति[भाग[2]]

        print("स्मृति लोड")


    elif यदि == "दर्शय":

        दर्शय()


    elif यदि == "स्मृति-दर्शय":

        स्मृति_दर्शय()


    else:

        print("अमान्य आदेश")


def कार्य_चलाओ():

    print("कार्य प्रारम्भ")

    for पंक्ति in कार्यसूची:

        आदेश_निष्पादन(पंक्ति)

    print("कार्य समाप्त")


सक्रिय = True

while सक्रिय:

    आदेश = input("यन्त्र >>> ")

    if आदेश == "निर्गम":

        print("आभासी यन्त्र बन्द")

        break


    elif आदेश == "सहायता":

        print("आदेश:")
        print("स्थापय अ 10")
        print("योग अ ब")
        print("स्मृति क अ")
        print("लोड ब क")
        print("दर्शय")
        print("स्मृति-दर्शय")
        print("जोड़ो आदेश")
        print("चलाओ")
        print("निर्गम")


    elif आदेश.startswith("जोड़ो"):

        नया = आदेश[5:]

        कार्यसूची.append(नया)

        print("कार्य जोड़ा गया")


    elif आदेश == "चलाओ":

        कार्य_चलाओ()


    else:

        आदेश_निष्पादन(आदेश)
