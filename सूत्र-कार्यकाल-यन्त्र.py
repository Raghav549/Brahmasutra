print("🕉️ सूत्र कार्यकाल यन्त्र सक्रिय")


रजिस्टर = {

    "अ": 0,
    "ब": 0,
    "स": 0,
    "द": 0

}


स्मृति = {}


def दर्शय():

    print("रजिस्टर स्थिति:")

    for नाम in रजिस्टर:

        print(नाम, "=", रजिस्टर[नाम])


def निष्पादन(पंक्ति):

    भाग = पंक्ति.strip().split()

    आदेश = भाग[0]


    if आदेश == "INST_SET":

        रजिस्टर[भाग[1]] = int(भाग[2])

        print("स्थापित")


    elif आदेश == "INST_ADD":

        रजिस्टर[भाग[1]] += रजिस्टर[भाग[2]]

        print("योग पूर्ण")


    elif आदेश == "INST_SUB":

        रजिस्टर[भाग[1]] -= रजिस्टर[भाग[2]]

        print("घटाव पूर्ण")


    elif आदेश == "INST_MUL":

        रजिस्टर[भाग[1]] *= रजिस्टर[भाग[2]]

        print("गुणन पूर्ण")


    elif आदेश == "INST_STORE":

        स्मृति[भाग[1]] = रजिस्टर[भाग[2]]

        print("स्मृति संग्रहीत")


    elif आदेश == "INST_LOAD":

        रजिस्टर[भाग[1]] = स्मृति[भाग[2]]

        print("स्मृति लोड")


    elif आदेश == "INST_PRINT":

        दर्शय()


    else:

        print("अज्ञात runtime आदेश")


def संचिका_चलाओ(नाम):

    with open(नाम, "r", encoding="utf-8") as f:

        पंक्तियाँ = f.readlines()


    print("कार्यकाल प्रारम्भ")


    for पंक्ति in पंक्तियाँ:

        निष्पादन(पंक्ति)


    print("कार्यकाल समाप्त")


नाम = input("संकलित संचिका नाम (.सूत्रक): ")

संचिका_चलाओ(नाम)
