"""🕉️ सूत्र-OS — the operating system, written as one सूत्र program.

The kernel is not a Python file that pretends to be an OS.  It is a program in
the project's own language (सूत्र), compiled to the project's own bytecode and
booted on the project's own VM.  Everything below runs inside
:func:`brahma_llm.kernel.boot`; nothing here imports Python's ``os``.

Subsystems, all self-tested at boot:

1. **स्मृति** — a first-fit allocator with a free list and byte accounting.
2. **प्रक्रिया** — a process table with pid allocation, priorities and states.
3. **अनुसूचक** — a round-robin scheduler with a per-process tick counter.
4. **आह्वान** — a syscall table (``sys_write`` … ``sys_time``) with counters.
5. **सञ्चिका** — an in-memory filesystem with inodes, sizes and listing.
6. **व्यवधान** — an interrupt counter with source tracking.

The boot contract is fixed: the banner, the line
``स्व-परीक्षण: ठीक / ठीक``, a subsystem summary and finally ``READY``.  A kernel
that fails any of those cannot be installed (see :func:`brahma_llm.kernel.verify`).
"""

