# 🕉️ सूत्र पूर्ण भाषा निष्पादन यन्त्र


class सूत्रयन्त्र:


    def __init__(self):

        self.चर = {}

        print("🕉️ सूत्र भाषा निष्पादन यन्त्र सक्रिय")


    def निष्पादन(self, संचिका):

        print(f"संचिका लोड: {संचिका}")


        with open(संचिका, "r", encoding="utf-8") as file:

            पंक्तियाँ = file.readlines()


        for पंक्ति in पंक्तियाँ:

            self.आदेश_चलाओ(पंक्ति.strip())


    def आदेश_चलाओ(self, आदेश):

        भाग = आदेश.split()


        if not भाग:

            return


        if भाग[0] == "संकल्प":

            नाम = भाग[1]

            मान = int(भाग[2])

            self.चर[नाम] = मान

            print(f"चर निर्मित: {नाम} = {मान}")


        elif भाग[0] == "योग":

            अ = भाग[1]

            ब = भाग[2]

            self.चर[अ] += self.चर[ब]

            print(f"योग पूर्ण: {अ} = {self.चर[अ]}")


        elif भाग[0] == "दर्शय":

            नाम = भाग[1]

            print(f"मान: {नाम} = {self.चर[नाम]}")


        elif भाग[0] == "निर्गम":

            print("निष्पादन समाप्त")

            exit()


        else:

            print(f"अज्ञात आदेश: {आदेश}")
