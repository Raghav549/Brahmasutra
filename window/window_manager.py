class सूत्रविंडोप्रबंधक:

    def __init__(self):

        self.विंडो_सूची = []

        print("सूत्र विंडो प्रबंधक आरम्भ")

    def विंडो_निर्माण(self, नाम):

        विंडो = {
            "नाम": नाम,
            "तत्व": []
        }

        self.विंडो_सूची.append(विंडो)

        print(f"विंडो निर्मित: {नाम}")

        return विंडो

    def पाठ_जोड़ें(self, विंडो, पाठ):

        विंडो["तत्व"].append(("पाठ", पाठ))

    def बटन_जोड़ें(self, विंडो, नाम):

        विंडो["तत्व"].append(("बटन", नाम))

    def प्रदर्शन(self):

        print("\n===== स्क्रीन =====\n")

        for विंडो in self.विंडो_सूची:

            print(f"विंडो: {विंडो['नाम']}")

            for प्रकार, मान in विंडो["तत्व"]:

                print(f"{प्रकार}: {मान}")

            print()
