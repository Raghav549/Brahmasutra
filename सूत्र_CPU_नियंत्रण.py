# 🕉️ सूत्र CPU नियंत्रण तंत्र

class सूत्रCPUनियंत्रण:


    def __init__(self):

        print("🕉️ सूत्र वास्तविक CPU नियंत्रण सक्रिय")

        self.रजिस्टर = {

            "अ":0,
            "ब":0,
            "स":0,
            "द":0

        }

        self.स्मृति = {}

        self.निर्देशसूची = []

        self.निर्देशसूचक = 0


    def स्मृतिलेखन(self, स्थान, मान):

        self.स्मृति[स्थान] = मान

        print("स्मृति लेखन:", स्थान, मान)


    def स्मृतिपठन(self, स्थान):

        मान = self.स्मृति.get(स्थान,0)

        print("स्मृति पठन:", स्थान, मान)

        return मान


    def निर्देशलोड(self, सूची):

        self.निर्देशसूची = सूची

        self.निर्देशसूचक = 0

        print("निर्देश लोड:", len(सूची))


    def निष्पादन(self):

        print("CPU निष्पादन प्रारम्भ")


        while self.निर्देशसूचक < len(self.निर्देशसूची):

            निर्देश = self.निर्देशसूची[self.निर्देशसूचक]

            self.चलाओ(निर्देश)

            self.निर्देशसूचक += 1


        print("CPU निष्पादन समाप्त")


    def चलाओ(self, निर्देश):

        भाग = निर्देश.split()


        if भाग[0] == "स्थापय":

            र = भाग[1]

            मान = int(भाग[2])

            self.रजिस्टर[र] = मान

            print("स्थापित:", र, मान)


        elif भाग[0] == "योग":

            र1 = भाग[1]

            र2 = भाग[2]

            self.रजिस्टर[र1] += self.रजिस्टर[र2]

            print("योग परिणाम:", self.रजिस्टर[र1])


        elif भाग[0] == "दर्शय":

            for र in self.रजिस्टर:

                print(र,"=",self.रजिस्टर[र])


        elif भाग[0] == "स्मृतिलेख":

            स्थान = int(भाग[1])

            मान = int(भाग[2])

            self.स्मृतिलेखन(स्थान,मान)


        elif भाग[0] == "स्मृतिपाठ":

            स्थान = int(भाग[1])

            self.स्मृतिपठन(स्थान)


        else:

            print("अज्ञात निर्देश:", निर्देश)
