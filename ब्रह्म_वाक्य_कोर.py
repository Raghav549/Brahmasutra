# 🕉️ ब्रह्म वाक्य कोर VERSION 2

print("🕉️ ब्रह्म वाक्य कोर सक्रिय")

class ब्रह्मवाक्यकोर:

    def __init__(self):

        self.मान्य_आदेश = [
            "स्थापित",
            "दर्शय",
            "योग"
        ]

    def विश्लेषण(self, वाक्य):

        वाक्य = वाक्य.strip()

        if वाक्य == "":
            return {
                "मान्य": False,
                "शब्द": []
            }

        शब्द = वाक्य.split()

        if शब्द[0] in self.मान्य_आदेश:

            return {
                "मान्य": True,
                "शब्द": शब्द
            }

        return {
            "मान्य": False,
            "शब्द": शब्द
        }
