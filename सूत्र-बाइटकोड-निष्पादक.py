रजिस्टर = {

    "अ": 0,
    "ब": 0,
    "स": 0,
    "द": 0

}


स्मृति = {}


कोड_से_आदेश = {

    "01": "स्थापय",
    "02": "योग",
    "03": "घटा",
    "04": "गुण",
    "05": "स्मृति",
    "06": "लोड",
    "07": "दर्शय"

}


def दर्शय():

    print("रजिस्टर स्थिति:")

    for नाम in रजिस्टर:

        print(नाम, "=", रजिस्टर[नाम])


def निष्पादन(पंक्ति):

    भाग = पंक्ति.strip().split()

    कोड = भाग[0]

    आदेश = कोड_से_आदेश.get(कोड)


    if आदेश == "स्थापय":

        रजिस्टर[भाग[1]] = int(भाग[2])

        print("स्थापित")


    elif आदेश == "योग":

        रजिस्टर[भाग[1]] += रजिस्टर[भाग[2]]

        print("योग पूर्ण")


    elif आदेश == "घटा":

        रजिस्टर[भाग[1]] -= रजिस्टर[भाग[2]]

        print("घटाव पूर्ण")


    elif आदेश == "गुण":

        रजिस्टर[भाग[1]] *= रजिस्टर[भाग[2]]

        print("गुणन पूर्ण")


    elif आदेश == "स्मृति":

        स्मृति[भाग[1]] = रजिस्टर[भाग[2]]

        print("स्मृति संग्रहीत")


    elif आदेश == "लोड":

        रजिस्टर[भाग[1]] = स्मृति[भाग[2]]

        print("लोड पूर्ण")


    elif आदेश == "दर्शय":

        दर्शय()


    else:

        print("अमान्य बाइटकोड")


def संचिका_चलाओ(नाम):

    with open(नाम, "r", encoding="utf-8") as f:

        पंक्तियाँ = f.readlines()


    print("बाइटकोड निष्पादन प्रारम्भ")


    for पंक्ति in पंक्तियाँ:

        निष्पादन(पंक्ति)


    print("बाइटकोड निष्पादन समाप्त")


