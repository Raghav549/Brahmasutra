#!/usr/bin/env python3
"""Record the current behaviour of the historical demo scripts.

The repository contains ~700 prototype files from several generations of the
project.  They are kept for provenance but are not part of the supported
engine (``brahma/``).  This tool snapshots their behaviour so that:

* regressions in working demos are visible in CI;
* the exact set of known-broken demos is recorded, not hidden.

Usage::

    python tools/legacy_baseline.py            # regenerate the baseline
    python tools/legacy_baseline.py --check    # fail if the set changed
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASELINE = os.path.join(REPO_ROOT, "tests", "legacy_baseline.json")

SCRIPT_PATTERN = re.compile(r"(^test.*|.*_test|.*परीक्षण.*)\.py$")

#: Modules that the current engine build is expected to import cleanly.
IMPORT_MODULES = [
    "सूत्र_CPU_v1",
    "सूत्र_machine_code",
    "सूत्र_machine_cpu",
    "सूत्र_parser",
    "सूत्र_bytecode",
    "सूत्र_संकलक",
    "सूत्र_व्याख्याकार",
    "सूत्र_shell",
    "सूत्र_shell_v2",
    "सूत्र_shell_v4",
    "सूत्र_scheduler",
    "सूत्र_process_manager_v2",
    "सूत्र_memory_protection",
    "सूत्र_memory_manager",
    "सूत्र_kernel_core",
    "सूत्र_kernel_filesystem",
    "सूत्र_syscall_core",
    "सूत्र_os_v3",
    "vm.sutra_vm",
    "vm.instructions",
    "vm.callstack",
    "kernel.kernel_engine",
    "compiler.compiler_engine",
]


def scripts():
    """Return every top-level legacy test/demo script."""
    found = []
    for name in sorted(os.listdir(REPO_ROOT)):
        path = os.path.join(REPO_ROOT, name)
        if os.path.isfile(path) and SCRIPT_PATTERN.search(name):
            found.append(name)
    return found


def run_script(name, timeout=10, cwd=None):
    try:
        completed = subprocess.run(
            [sys.executable, name],
            cwd=cwd or REPO_ROOT,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=timeout,
        )
    except subprocess.TimeoutExpired:
        return {"status": "timeout", "exit": None, "reason": "केवल %ds में समाप्त नहीं हुआ" % timeout}
    stderr = completed.stderr.decode("utf-8", "replace").strip().splitlines()
    reason = stderr[-1][:160] if stderr else ""
    status = "pass" if completed.returncode == 0 else "fail"
    return {"status": status, "exit": completed.returncode, "reason": reason}


def check_import(module):
    try:
        completed = subprocess.run(
            [sys.executable, "-c", "import %s" % module],
            cwd=REPO_ROOT,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=10,
        )
    except subprocess.TimeoutExpired:
        return {"status": "timeout", "reason": ""}
    if completed.returncode == 0:
        return {"status": "pass", "reason": ""}
    stderr = completed.stderr.decode("utf-8", "replace").strip().splitlines()
    return {"status": "fail", "reason": stderr[-1][:160] if stderr else ""}


def build():
    """Run every demo in a throw-away copy so the checkout stays clean."""
    data = {
        "note": "Generated by tools/legacy_baseline.py — do not edit by hand.",
        "python": "%d.%d" % sys.version_info[:2],
        "scripts": {},
        "modules": {},
    }
    workdir = tempfile.mkdtemp(prefix="brahma-legacy-")
    sandbox = os.path.join(workdir, "repo")
    shutil.copytree(
        REPO_ROOT,
        sandbox,
        ignore=shutil.ignore_patterns(".git", "__pycache__", ".venv", "*.pyc"),
        symlinks=True,
    )
    try:
        for name in scripts():
            data["scripts"][name] = run_script(name, cwd=sandbox)
            print("%-40s %s" % (name, data["scripts"][name]["status"]))
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
    for module in IMPORT_MODULES:
        data["modules"][module] = check_import(module)
    return data


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the recorded set of scripts changed")
    parser.add_argument("--output", default=BASELINE)
    args = parser.parse_args(argv)

    if args.check:
        with open(args.output, encoding="utf-8") as handle:
            data = json.load(handle)
        recorded = set(data.get("scripts", {}))
        current = set(scripts())
        missing = sorted(current - recorded)
        stale = sorted(recorded - current)
        if missing or stale:
            print("baseline out of date")
            print("  new scripts:", missing)
            print("  removed scripts:", stale)
            return 1
        print("baseline covers %d scripts" % len(recorded))
        return 0

    data = build()
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as handle:
        json.dump(data, handle, ensure_ascii=False, indent=2, sort_keys=True)
        handle.write("\n")
    passed = sum(1 for v in data["scripts"].values() if v["status"] == "pass")
    print("\n%d/%d legacy scripts pass" % (passed, len(data["scripts"])))
    print("baseline written to %s" % args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
