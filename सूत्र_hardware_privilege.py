# 🕉️ सूत्र हार्डवेयर विशेषाधिकार तंत्र

class विशेषाधिकार_स्तर:

    कर्ण = 0
    उपयोगकर्ता = 3


class सूत्र_CPU:

    def __init__(self):

        self.वर्तमान_स्तर = विशेषाधिकार_स्तर.उपयोगकर्ता

        print("🕉️ सूत्र CPU विशेषाधिकार तंत्र सक्रिय")


    def स्तर_स्थिति(self):

        if self.वर्तमान_स्तर == विशेषाधिकार_स्तर.कर्ण:

            print("वर्तमान स्तर: कर्ण")

        else:

            print("वर्तमान स्तर: उपयोगकर्ता")


    def कर्ण_प्रवेश(self):

        print("कर्ण स्तर प्रवेश")

        self.वर्तमान_स्तर = विशेषाधिकार_स्तर.कर्ण


    def उपयोगकर्ता_प्रवेश(self):

        print("उपयोगकर्ता स्तर प्रवेश")

        self.वर्तमान_स्तर = विशेषाधिकार_स्तर.उपयोगकर्ता


    def विशेषाधिकार_जांच(self):

        if self.वर्तमान_स्तर != विशेषाधिकार_स्तर.कर्ण:

            print("❌ विशेषाधिकार त्रुटि: कर्ण स्तर आवश्यक")

            return False

        return True


    def संरक्षित_आदेश(self):

        if not self.विशेषाधिकार_जांच():

            return

        print("✔ संरक्षित आदेश सफल")
