# 🕉️ सूत्र पूर्ण संचालन तंत्र

import सूत्र_पूर्ण_कर्ण as kernel


class सूत्रOS:


    def __init__(self):

        print("🕉️ सूत्र संचालन तंत्र सक्रिय")

        self.kernel = kernel.सूत्रकर्ण()


    def boot(self):

        print("Boot प्रारम्भ")

        self.kernel.प्रारम्भ()

        print("OS पूर्ण सक्रिय")
