# 🕉️ सूत्र प्रक्रिया तंत्र


class प्रक्रिया:


    def __init__(self, नाम):

        self.नाम = नाम

        self.स्थिति = "निर्मित"


    def चलाओ(self):

        self.स्थिति = "चल रहा"

        print(f"प्रक्रिया चल रही: {self.नाम}")


    def बन्द(self):

        self.स्थिति = "बन्द"

        print(f"प्रक्रिया बन्द: {self.नाम}")



class प्रक्रिया_प्रबंधक:


    def __init__(self):

        self.प्रक्रियाएँ = {}

        print("🕉️ प्रक्रिया प्रबंधक निर्मित")


    def निर्माण(self, नाम):

        p = प्रक्रिया(नाम)

        self.प्रक्रियाएँ[नाम] = p

        print(f"प्रक्रिया निर्मित: {नाम}")

        return p


    def चलाओ(self, नाम):

        if नाम in self.प्रक्रियाएँ:

            self.प्रक्रियाएँ[नाम].चलाओ()

        else:

            print("त्रुटि: प्रक्रिया नहीं मिला")


    def सूची(self):

        print("प्रक्रिया सूची:")

        for नाम in self.प्रक्रियाएँ:

            स्थिति = self.प्रक्रियाएँ[नाम].स्थिति

            print(f"{नाम} : {स्थिति}")


# global instance

प्रबंधक = प्रक्रिया_प्रबंधक()


