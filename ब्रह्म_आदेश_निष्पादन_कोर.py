from ब्रह्म_CPU_कोर import ब्रह्मCPUकोर


class ब्रह्मआदेशनिष्पादनकोर:

    def __init__(self):

        self.cpu = ब्रह्मCPUकोर()

        print("आदेश निष्पादन प्रणाली तैयार")


    def आदेश_चलाओ(self, आदेश):

        भाग = आदेश.strip().split()

        if len(भाग) == 0:
            return

        cmd = भाग[0]


        if cmd == "स्थापित":

            नाम = भाग[1]

            मान = int(भाग[2])

            self.cpu.स्थापित(नाम, मान)


        elif cmd == "योग":

            लक्ष्य = भाग[1]

            स्रोत = भाग[2]

            self.cpu.योग(लक्ष्य, स्रोत)


        elif cmd == "घटाव":

            लक्ष्य = भाग[1]

            स्रोत = भाग[2]

            self.cpu.घटाव(लक्ष्य, स्रोत)


        elif cmd == "गुणा":

            लक्ष्य = भाग[1]

            स्रोत = भाग[2]

            self.cpu.गुणा(लक्ष्य, स्रोत)


        elif cmd == "दर्शय":

            नाम = भाग[1]

            self.cpu.दर्शय(नाम)


        else:

            print("अमान्य आदेश:", आदेश)


    def निष्पादन(self, संचिका):

        print("निष्पादन प्रारम्भ")

        try:

            with open(संचिका, "r", encoding="utf-8") as f:

                lines = f.readlines()

            for line in lines:

                self.आदेश_चलाओ(line)

            print("निष्पादन पूर्ण")

        except:

            print("त्रुटि: संचिका नहीं मिली")


