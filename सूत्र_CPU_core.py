# सूत्र तंत्र — CPU Core

print("सूत्र CPU Core सक्रिय")



रजिस्टर = {

    "अ": 0,
    "ब": 0,
    "स": 0,
    "द": 0

}



def चलाओ(निर्देश, op1=None, op2=None):

    if निर्देश == "लोड":

        रजिस्टर[op1] = op2


    elif निर्देश == "योग":

        रजिस्टर[op1] += रजिस्टर[op2]


    elif निर्देश == "गुण":

        रजिस्टर[op1] *= रजिस्टर[op2]


    elif निर्देश == "दर्शय":

        print("मान:", रजिस्टर[op1])



चलाओ("लोड", "अ", 10)
चलाओ("लोड", "ब", 5)
चलाओ("योग", "अ", "ब")
चलाओ("दर्शय", "अ")
