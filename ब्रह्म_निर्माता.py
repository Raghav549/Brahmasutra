print("🕉️ ब्रह्म निर्माता प्रणाली प्रारम्भ")


import os


class ब्रह्मनिर्माता:

    def __init__(self):

        print("ब्रह्म निर्माता सक्रिय")

        self.पथ = os.path.expanduser("~/सूत्र-तंत्र/ब्रह्म_अनुप्रयोग")

        if not os.path.exists(self.पथ):

            os.makedirs(self.पथ)


    # ============================================
    # अनुप्रयोग निर्माण
    # ============================================

    def निर्माण(self, नाम, विश्लेषण):

        संचिका = f"{self.पथ}/{नाम}.सूत्र"

        with open(संचिका, "w", encoding="utf-8") as f:

            f.write("कार्य प्रारम्भ\n")

            f.write('    दर्शय "🕉️ ब्रह्म अनुप्रयोग प्रारम्भ"\n')


            if "प्रवेश प्रणाली" in विश्लेषण["घटक"]:

                f.write('    दर्शय "प्रवेश प्रणाली सक्रिय"\n')


            if "संवाद तंत्र" in विश्लेषण["घटक"]:

                f.write('    दर्शय "संवाद तंत्र सक्रिय"\n')


            if "एपीआई तंत्र" in विश्लेषण["घटक"]:

                f.write('    दर्शय "एपीआई तंत्र सक्रिय"\n')


            if "संग्रह तंत्र" in विश्लेषण["घटक"]:

                f.write('    दर्शय "संग्रह तंत्र सक्रिय"\n')


            f.write('    दर्शय "अनुप्रयोग सफल"\n')


        print("अनुप्रयोग निर्मित:", संचिका)

        return संचिका
