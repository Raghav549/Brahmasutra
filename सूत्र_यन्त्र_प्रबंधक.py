# 🕉️ सूत्र यन्त्र प्रबंधक

class सूत्रयन्त्रप्रबंधक:

    def __init__(self):

        print("🕉️ सूत्र यन्त्र प्रबंधक सक्रिय")

        self.यन्त्र = {}


    def पंजीकरण(self, नाम):

        self.यन्त्र[नाम] = True

        print("यन्त्र पंजीकृत:", नाम)


    def सूची(self):

        print("उपलब्ध यन्त्र:")

        for य in self.यन्त्र:

            print("•", य)
