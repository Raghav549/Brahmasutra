from ब्रह्म_कोर import ब्रह्मकोर
from ब्रह्म_विश्लेषण import ब्रह्मविश्लेषक
from ब्रह्म_निर्माता import ब्रह्मनिर्माता

print("🕉️ ब्रह्म प्रवेश प्रणाली प्रारम्भ")


class ब्रह्मप्रवेश:

    def __init__(self):

        self.कोर = ब्रह्मकोर()

        self.विश्लेषक = ब्रह्मविश्लेषक()

        self.निर्माता = ब्रह्मनिर्माता()

        self.कोर.प्रारम्भ()

        print("ब्रह्म प्रवेश प्रणाली सक्रिय")


    def प्रवेश_ग्रहण(self):

        while True:

            प्रवेश = input("ब्रह्म >>> ")

            if प्रवेश == "निर्गम":

                print("ब्रह्म समाप्त")

                break

            if प्रवेश == "स्थिति":

                self.कोर.स्थिति_दर्शय()

                continue

            self.स्मृति_संग्रह(प्रवेश)

            विश्लेषण = self.विश्लेषक.विश्लेषण(प्रवेश)

            नाम = f"अनुप्रयोग_{len(self.कोर.स्मृति)}"

            self.निर्माता.निर्माण(नाम, विश्लेषण)


    def स्मृति_संग्रह(self, प्रवेश):

        क्रम = len(self.कोर.स्मृति) + 1

        self.कोर.स्मृति[क्रम] = प्रवेश

        print("संग्रहीत:", प्रवेश)


if __name__ == "__main__":

    प्रणाली = ब्रह्मप्रवेश()

    प्रणाली.प्रवेश_ग्रहण()
