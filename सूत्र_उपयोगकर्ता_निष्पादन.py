# 🕉️ सूत्र उपयोगकर्ता स्तर निष्पादन तंत्र


import सूत्र_आह्वान_तंत्र as आह्वान


class उपयोगकर्ताकार्य:


    def __init__(self, नाम):

        self.नाम = नाम

        self.स्थिति = "तैयार"


    def चलाओ(self):

        self.स्थिति = "सक्रिय"

        print(f"उपयोगकर्ता कार्य चल रहा है: {self.नाम}")



class उपयोगकर्तातंत्र:


    def __init__(self):

        self.कार्यसूची = []

        self.कर्ण = आह्वान.आह्वानतंत्र()

        print("🕉️ उपयोगकर्ता स्तर तंत्र सक्रिय")


    def निर्माण(self, नाम):

        कार्य = उपयोगकर्ताकार्य(नाम)

        self.कार्यसूची.append(कार्य)

        print(f"कार्य निर्मित: {नाम}")

        return कार्य


    def निष्पादन(self, कार्य):

        print("उपयोगकर्ता स्तर निष्पादन प्रारम्भ")

        कार्य.चलाओ()

        print("उपयोगकर्ता स्तर निष्पादन समाप्त")
