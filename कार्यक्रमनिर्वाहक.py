# सूत्र तंत्र — कार्यक्रम-निर्वाहक

from निर्वाहक import निर्वाह


def कार्यक्रम_चलाओ(सञ्चिका_नाम):

    print("सूत्र कार्यक्रम प्रारम्भ")

    try:

        with open(सञ्चिका_नाम, encoding="utf-8") as सञ्चिका:

            पंक्तियाँ = सञ्चिका.readlines()

            for पंक्ति in पंक्तियाँ:

                पंक्ति = पंक्ति.strip()

                if पंक्ति != "":

                    निर्वाह(पंक्ति)

    except FileNotFoundError:

        print("सञ्चिका न प्राप्ता")


def परीक्षण():

    सञ्चिका_नाम = "कार्यक्रम.सूत्र"

    कार्यक्रम_चलाओ(सञ्चिका_नाम)


if __name__ == "__main__":
    परीक्षण()
