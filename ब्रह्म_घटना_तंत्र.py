# ब्रह्म घटना तंत्र

class ब्रह्मघटनातंत्र:

    def __init__(self):
        self.घटनाएँ = {}
        print("🕉️ ब्रह्म घटना तंत्र सक्रिय")


    def पंजीकरण(self, घटना_नाम, कार्य):

        if घटना_नाम not in self.घटनाएँ:
            self.घटनाएँ[घटना_नाम] = []

        self.घटनाएँ[घटना_नाम].append(कार्य)

        print(f"घटना पंजीकृत: {घटना_नाम}")


    def सक्रिय_करें(self, घटना_नाम, डेटा=None):

        print(f"घटना सक्रिय: {घटना_नाम}")

        if घटना_नाम not in self.घटनाएँ:
            print("कोई श्रोता नहीं")
            return

        for कार्य in self.घटनाएँ[घटना_नाम]:
            कार्य(डेटा)


    def सूची(self):

        return list(self.घटनाएँ.keys())
