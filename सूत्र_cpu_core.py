# 🕉️ सूत्र स्वदेशी CPU Core


class सूत्रCPU:


    def __init__(self):

        self.रजिस्टर = {

            "अ": 0,
            "ब": 0,
            "स": 0,
            "द": 0

        }

        print("🕉️ सूत्र CPU सक्रिय")


    def स्थापित(self, रजिस्टर, मान):

        self.रजिस्टर[रजिस्टर] = मान

        print(f"स्थापित: {रजिस्टर} = {मान}")


    def योग(self, र1, र2):

        परिणाम = self.रजिस्टर[र1] + self.रजिस्टर[र2]

        self.रजिस्टर[र1] = परिणाम

        print(f"योग परिणाम: {र1} = {परिणाम}")


    def घटाव(self, र1, र2):

        परिणाम = self.रजिस्टर[र1] - self.रजिस्टर[र2]

        self.रजिस्टर[र1] = परिणाम

        print(f"घटाव परिणाम: {र1} = {परिणाम}")


    def दर्शय(self):

        print("CPU रजिस्टर स्थिति:")

        for र in self.रजिस्टर:

            print(f"{र} = {self.रजिस्टर[र]}")
