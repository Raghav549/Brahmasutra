# 🕉️ सूत्र प्रक्रिया वस्तु

class प्रक्रिया:

    def __init__(self, नाम, मोड):

        self.नाम = नाम
        self.मोड = मोड
        self.स्मृति = {}
        self.सक्रिय = True


    def स्थिति(self):

        print("प्रक्रिया:", self.नाम)
        print("मोड:", self.मोड)
        print("सक्रिय:", self.सक्रिय)


    def स्मृति_स्थापित(self, कुंजी, मान):

        if self.मोड != "कर्ण":

            print("सुरक्षा त्रुटि: उपयोगकर्ता कर्ण स्मृति नहीं बदल सकता")
            return

        self.स्मृति[कुंजी] = मान
        print("स्मृति स्थापित:", कुंजी)


    def स्मृति_पठन(self, कुंजी):

        return self.स्मृति.get(कुंजी, None)
