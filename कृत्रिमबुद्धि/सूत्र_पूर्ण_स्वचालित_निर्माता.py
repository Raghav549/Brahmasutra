# 🕉️ सूत्र पूर्ण स्वचालित अनुप्रयोग निर्माण तंत्र

import os

from सूत्र_अनुप्रयोग_निर्माता import सूत्रअनुप्रयोगनिर्माता


class सूत्रपूर्णस्वचालितनिर्माता:


    def __init__(self):

        print("🕉️ सूत्र पूर्ण स्वचालित निर्माण तंत्र सक्रिय")

        self.निर्माता = सूत्रअनुप्रयोगनिर्माता()

        self.पथ = "../अनुप्रयोग"

        self.द्विआधारीपथ = "../द्विआधारी"

        if not os.path.exists(self.द्विआधारीपथ):

            os.makedirs(self.द्विआधारीपथ)


    def संकलन(self, नाम):

        स्रोत = self.पथ + "/" + नाम + ".सूत्र"

        लक्ष्य = self.द्विआधारीपथ + "/" + नाम + ".सूत्रबिन"


        with open(स्रोत,"r",encoding="utf-8") as f:

            कोड = f.read()


        द्विआधारी = कोड.encode("utf-8")


        with open(लक्ष्य,"wb") as f:

            f.write(द्विआधारी)


        print("द्विआधारी निर्मित:", लक्ष्य)


    def निष्पादन(self, नाम):

        लक्ष्य = self.द्विआधारीपथ + "/" + नाम + ".सूत्रबिन"


        print("निष्पादन प्रारम्भ:", लक्ष्य)


        with open(लक्ष्य,"rb") as f:

            कोड = f.read().decode("utf-8")


        print("प्रोग्राम output:")

        print(कोड)


    def पूर्णनिर्माण(self, नाम):

        print("अनुप्रयोग निर्माण प्रारम्भ:", नाम)

        self.निर्माता.सूत्र_अनुप्रयोग_निर्माण(नाम)

        self.संकलन(नाम)

        self.निष्पादन(नाम)

        print("पूर्ण निर्माण समाप्त")
