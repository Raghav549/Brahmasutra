# 🕉️ सूत्र स्वनिर्णायक कृत्रिमबुद्धि

import random
import os

from सूत्र_पूर्ण_स्वचालित_निर्माता import सूत्रपूर्णस्वचालितनिर्माता


class सूत्रस्वनिर्णायककृत्रिमबुद्धि:


    def __init__(self):

        print("🕉️ सूत्र स्वनिर्णायक कृत्रिमबुद्धि सक्रिय")

        self.निर्माता = सूत्रपूर्णस्वचालितनिर्माता()

        self.नामसूची = [

            "गणक",

            "स्मृतिपरीक्षक",

            "संख्यापरीक्षक",

            "योगतंत्र",

            "विश्लेषक",

            "नियंत्रक",

            "दर्शक",

            "सहायक"

        ]


    def निर्णय(self):

        नाम = random.choice(self.नामसूची)

        print("निर्णय:", नाम)

        return नाम


    def निर्माण(self):

        नाम = self.निर्णय()

        self.निर्माता.पूर्णनिर्माण(नाम)


    def निरंतर(self):

        while True:

            आदेश = input("AI आदेश (निर्माण / निर्गम): ")

            if आदेश == "निर्माण":

                self.निर्माण()

            elif आदेश == "निर्गम":

                print("AI बन्द")

                break

            else:

                print("अमान्य आदेश")
