# 🕉️ ब्रह्म प्रक्रिया अनुसूचक

import time

class ब्रह्मप्रक्रियाअनुसूचक:

    def __init__(self):

        print("🕉️ ब्रह्म प्रक्रिया अनुसूचक सक्रिय")

        self.प्रक्रियाएँ = []
        self.चल_रही = None

    def जोड़ें(self, नाम, कार्य, प्राथमिकता=1):

        प्रक्रिया = {
            "नाम": नाम,
            "कार्य": कार्य,
            "प्राथमिकता": प्राथमिकता,
            "स्थिति": "प्रतीक्षा"
        }

        self.प्रक्रियाएँ.append(प्रक्रिया)

        print(f"प्रक्रिया जोड़ी गई: {नाम} (प्राथमिकता {प्राथमिकता})")

    def अनुसूचित_करें(self):

        if not self.प्रक्रियाएँ:

            print("कोई प्रक्रिया नहीं")

            return None

        # highest priority first
        self.प्रक्रियाएँ.sort(
            key=lambda x: x["प्राथमिकता"],
            reverse=True
        )

        प्रक्रिया = self.प्रक्रियाएँ.pop(0)

        self.चल_रही = प्रक्रिया

        प्रक्रिया["स्थिति"] = "चल रही"

        print(f"प्रक्रिया चयनित: {प्रक्रिया['नाम']}")

        return प्रक्रिया

    def चलाएँ(self):

        प्रक्रिया = self.अनुसूचित_करें()

        if प्रक्रिया is None:

            return

        try:

            प्रक्रिया["कार्य"]()

            प्रक्रिया["स्थिति"] = "समाप्त"

            print(f"प्रक्रिया समाप्त: {प्रक्रिया['नाम']}")

        except Exception as e:

            print("त्रुटि:", e)

    def सभी_चलाएँ(self):

        while self.प्रक्रियाएँ:

            self.चलाएँ()

            time.sleep(0.5)

    def स्थिति(self):

        print("\nस्थिति रिपोर्ट:\n")

        if self.चल_रही:

            print("चल रही:", self.चल_रही["नाम"])

        else:

            print("कोई प्रक्रिया नहीं चल रही")
