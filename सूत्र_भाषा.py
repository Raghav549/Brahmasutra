print("🕉️ सूत्र भाषा सक्रिय")
print("निर्गम लिखकर बाहर जाएँ")


# स्मृति
चर = {}


def दर्शय(नाम):

    if नाम in चर:

        print(नाम, "=", चर[नाम])

    else:

        print("अज्ञात चर")


def स्थापय(नाम, मान):

    चर[नाम] = int(मान)

    print("स्थापित:", नाम)


def योग(क, ख):

    if क in चर and ख in चर:

        चर[क] += चर[ख]

        print("योग पूर्ण")

    else:

        print("त्रुटि")


def घटा(क, ख):

    if क in चर and ख in चर:

        चर[क] -= चर[ख]

        print("घटाव पूर्ण")


def गुण(क, ख):

    if क in चर and ख in चर:

        चर[क] *= चर[ख]

        print("गुणन पूर्ण")


def आदेश_चलाओ(पंक्ति):

    भाग = पंक्ति.split()

    if len(भाग) == 0:
        return


    आदेश = भाग[0]


    if आदेश == "स्थापय":

        स्थापय(भाग[1], भाग[2])


    elif आदेश == "योग":

        योग(भाग[1], भाग[2])


    elif आदेश == "घटा":

        घटा(भाग[1], भाग[2])


    elif आदेश == "गुण":

        गुण(भाग[1], भाग[2])


    elif आदेश == "दर्शय":

        दर्शय(भाग[1])


    else:

        print("अज्ञात आदेश")


while True:

    पंक्ति = input("सूत्र >>> ")

    if पंक्ति == "निर्गम":

        print("सूत्र भाषा बन्द")

        break


    आदेश_चलाओ(पंक्ति)
