# 🕉️ सूत्र स्मृति संरक्षण तंत्र


class स्मृति_खंड:


    def __init__(self, नाम, आकार):

        self.नाम = नाम
        self.आकार = आकार
        self.डेटा = [0] * आकार
        self.सक्रिय = True


class सूत्रस्मृतिप्रबंधक:


    def __init__(self):

        self.खंडसूची = {}

        print("🕉️ स्मृति संरक्षण तंत्र सक्रिय")


    def आवंटन(self, नाम, आकार):

        if नाम in self.खंडसूची:

            print("त्रुटि: स्मृति पहले से आवंटित")

            return None


        खंड = स्मृति_खंड(नाम, आकार)

        self.खंडसूची[नाम] = खंड

        print("स्मृति आवंटित:", नाम, आकार)

        return खंड


    def लेखन(self, नाम, स्थान, मान):

        if नाम not in self.खंडसूची:

            print("त्रुटि: स्मृति नहीं मिली")

            return


        खंड = self.खंडसूची[नाम]


        if स्थान >= खंड.आकार:

            print("त्रुटि: सीमा से बाहर")

            return


        खंड.डेटा[स्थान] = मान

        print("स्मृति लेखन:", नाम, स्थान, मान)


    def पठन(self, नाम, स्थान):

        if नाम not in self.खंडसूची:

            print("त्रुटि: स्मृति नहीं मिली")

            return None


        खंड = self.खंडसूची[नाम]


        if स्थान >= खंड.आकार:

            print("त्रुटि: सीमा से बाहर")

            return None


        मान = खंड.डेटा[स्थान]

        print("स्मृति पठन:", नाम, स्थान, मान)

        return मान


    def मुक्त(self, नाम):

        if नाम in self.खंडसूची:

            del self.खंडसूची[नाम]

            print("स्मृति मुक्त:", नाम)
