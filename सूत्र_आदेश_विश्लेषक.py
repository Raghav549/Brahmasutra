# 🕉️ सूत्र आदेश विश्लेषक v3 — नियंत्रण संरचना सहित


import सूत्र_cpu_core as cpu


class आदेशविश्लेषक:


    def __init__(self):

        self.cpu = cpu.सूत्रCPU()

        print("🕉️ आदेश विश्लेषक सक्रिय")


    def शर्त_सत्य(self, र, मान):

        return self.cpu.रजिस्टर.get(र, 0) == मान


    def चलाओ(self, आदेश):

        भाग = आदेश.split()

        if len(भाग) == 0:
            return


        क्रिया = भाग[0]


        # संकल्प
        if क्रिया == "संकल्प":

            र = भाग[1]
            मान = int(भाग[2])

            self.cpu.स्थापित(र, मान)


        # योग
        elif क्रिया == "योग":

            र1 = भाग[1]
            र2 = भाग[2]

            self.cpu.योग(र1, र2)


        # घटाव
        elif क्रिया == "घटाव":

            र1 = भाग[1]
            र2 = भाग[2]

            self.cpu.घटाव(र1, र2)


        # दर्शय
        elif क्रिया == "दर्शय":

            self.cpu.दर्शय()


        # यदि condition
        elif क्रिया == "यदि":

            र = भाग[1]
            मान = int(भाग[2])

            if self.शर्त_सत्य(र, मान):

                print("शर्त सत्य है")

            else:

                print("शर्त असत्य है")


        # चक्र (loop)
        elif क्रिया == "चक्र":

            गिनती = int(भाग[1])

            for i in range(गिनती):

                print(f"चक्र iteration {i+1}")


        # निर्गम
        elif क्रिया == "निर्गम":

            print("प्रोग्राम समाप्त")
            exit()


        else:

            print("अज्ञात आदेश:", आदेश)
