# 🕉️ सूत्र कर्ण सञ्चिका एकीकरण


import सूत्र_सञ्चिका_कर्ण as सञ्चिका


class कर्णसञ्चिकातंत्र:


    def __init__(self):

        self.तंत्र = सञ्चिका.सञ्चिकातंत्र()

        print("🕉️ कर्ण सञ्चिका तंत्र जुड़ गया")


    def आदेश(self, इनपुट):

        भाग = इनपुट.split()


        if भाग[0] == "निर्माण":

            self.तंत्र.निर्माण(भाग[1])


        elif भाग[0] == "लेखन":

            नाम = भाग[1]

            सामग्री = " ".join(भाग[2:])

            self.तंत्र.लेखन(नाम, सामग्री)


        elif भाग[0] == "पठन":

            self.तंत्र.पठन(भाग[1])


        elif भाग[0] == "सूची":

            self.तंत्र.सूची()


        else:

            print("❌ अज्ञात सञ्चिका आदेश")
