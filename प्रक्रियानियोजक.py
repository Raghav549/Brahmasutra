# प्रक्रिया सूची
प्रक्रियासूची = []

# वर्तमान प्रक्रिया
वर्तमान = None


# नई प्रक्रिया बनाओ
def प्रक्रिया_निर्माण(नाम):

    प्रक्रिया = {

        "नाम": नाम,
        "स्थिति": "प्रतीक्षा"

    }

    प्रक्रियासूची.append(प्रक्रिया)

    print("नई प्रक्रिया बनी:", नाम)


# प्रक्रिया चलाओ
def प्रक्रिया_चलाओ():

    global वर्तमान

    if len(प्रक्रियासूची) == 0:

        print("कोई प्रक्रिया नहीं")
        return

    वर्तमान = प्रक्रियासूची.pop(0)

    वर्तमान["स्थिति"] = "चल रही"

    print("प्रक्रिया चल रही:", वर्तमान["नाम"])


# प्रक्रिया समाप्त करो
def प्रक्रिया_समाप्त():

    global वर्तमान

    if वर्तमान == None:

        print("कोई सक्रिय प्रक्रिया नहीं")

        return

    print("प्रक्रिया समाप्त:", वर्तमान["नाम"])

    वर्तमान = None


# प्रक्रिया स्थिति दिखाओ
def प्रक्रिया_स्थिति():

    print("प्रतीक्षा सूची:")

    for प्रक्रिया in प्रक्रियासूची:

        print(प्रक्रिया["नाम"], प्रक्रिया["स्थिति"])

    if वर्तमान:

        print("सक्रिय:", वर्तमान["नाम"])


