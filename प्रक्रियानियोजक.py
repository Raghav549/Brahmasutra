# ---------------------------------------------------------------------------
def _main():
    print("प्रक्रिया नियोजक आरम्भ")


    # TEST

    प्रक्रिया_निर्माण("गणक")
    प्रक्रिया_निर्माण("लेखक")
    प्रक्रिया_निर्माण("दर्शक")

    प्रक्रिया_स्थिति()

    प्रक्रिया_चलाओ()

    प्रक्रिया_स्थिति()

    प्रक्रिया_समाप्त()

    प्रक्रिया_स्थिति()

    print("प्रक्रिया नियोजक सक्रिय")


